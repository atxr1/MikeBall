def glyph_name(ch):
    return "space" if ch == " " else f"uni{ord(ch):04X}"


def draw(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        c = 0
        while c < len(row):
            if row[c] != "#":
                c += 1
                continue
            start = c
            while c < len(row) and row[c] == "#":
                c += 1
            x0 = start * U
            x1 = c * U
            y1 = (7 - r) * U
            y0 = y1 - U
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y1))
            pen.lineTo((x1, y1))
            pen.lineTo((x1, y0))
            pen.closePath()
    return pen.glyph()


def main():
    order = [".notdef", "space"] + [glyph_name(ch) for ch in G]
    fb = FontBuilder(EM, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {32: "space"}
    for ch in G:
        cmap[ord(ch)] = glyph_name(ch)
    fb.setupCharacterMap(cmap)
    glyphs = {".notdef": TTGlyphPen(None).glyph(), "space": TTGlyphPen(None).glyph()}
    metrics = {".notdef": (500, 0), "space": (400, 0)}
    for ch, rows in G.items():
        name = glyph_name(ch)
        glyphs[name] = draw(rows)
        width = max(len(r) for r in rows)
        metrics[name] = (int((width + 1) * U), 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "MikeBall Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200, sxHeight=500, sCapHeight=700)
    fb.setupPost()
    out = Path(__file__).resolve().parent.parent / "fonts"
    out.mkdir(exist_ok=True)
    fb.save(str(out / "mikeball-pixel.ttf"))
    fb.font.flavor = "woff"
    fb.save(str(out / "mikeball-pixel.woff"))
    print("wrote", out / "mikeball-pixel.woff")


if __name__ == "__main__":
    main()
